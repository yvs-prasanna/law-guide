import React, { useState } from 'react';
import { useLocation, useNavigate, Link } from 'react-router-dom';
import { 
  ArrowLeft, Scale, Bookmark, Check, ExternalLink, 
  AlertTriangle, Shield, CheckCircle2 
} from 'lucide-react';
import { saveCase } from '../services/api';

export default function CaseDetails({ user }) {
  const location = useLocation();
  const navigate = useNavigate();

  const caseItem = location.state?.caseItem;
  const userQuery = location.state?.userQuery;
  const problem_summary = location.state?.problem_summary;

  const [saved, setSaved] = useState(false);
  const [saving, setSaving] = useState(false);
  const [saveMessage, setSaveMessage] = useState(null);

  if (!caseItem) {
    return (
      <div style={{ textAlign: 'center', padding: '4rem 1.5rem' }}>
        <Scale size={48} style={{ color: 'var(--text-light)', marginBottom: '1rem' }} />
        <h2>Case Details Not Found</h2>
        <p style={{ color: 'var(--text-muted)', marginBottom: '1.5rem' }}>
          No case was selected for detailed inspection.
        </p>
        <Link to="/" className="btn btn-primary">
          <ArrowLeft size={16} />
          <span>Return to Homepage</span>
        </Link>
      </div>
    );
  }

  const isVerified = caseItem.verification_status === 'verified';

  const handleSave = async () => {
    if (!user) {
      alert('Please sign in with Google to save cases.');
      navigate('/login');
      return;
    }

    setSaving(true);
    try {
      await saveCase({
        case_title: caseItem.case_title,
        court: caseItem.court,
        citation: caseItem.citation,
        source_url: caseItem.source_url,
        case_data: caseItem,
      });
      setSaved(true);
      setSaveMessage('Case saved to your research library.');
      setTimeout(() => setSaveMessage(null), 4000);
    } catch (err) {
      alert(err.message || 'Error saving case.');
    } finally {
      setSaving(false);
    }
  };

  return (
    <div style={{ maxWidth: '860px', margin: '0 auto' }}>
      {/* Back button */}
      <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '1.5rem' }}>
        <button onClick={() => navigate(-1)} className="btn btn-secondary btn-sm">
          <ArrowLeft size={16} />
          <span>Back</span>
        </button>

        <div style={{ display: 'flex', gap: '0.75rem' }}>
          {caseItem.source_url && (
            <a
              href={caseItem.source_url}
              target="_blank"
              rel="noopener noreferrer"
              className="btn btn-secondary btn-sm"
            >
              <ExternalLink size={14} />
              <span>Open Source Document</span>
            </a>
          )}

          <button
            onClick={handleSave}
            disabled={saved || saving}
            className={`btn btn-sm ${saved ? 'btn-outline-gold' : 'btn-primary'}`}
          >
            {saved ? <Check size={14} /> : <Bookmark size={14} />}
            <span>{saved ? 'Saved in Library' : 'Save to My Cases'}</span>
          </button>
        </div>
      </div>

      {saveMessage && (
        <div className="alert alert-info" style={{ display: 'flex', alignItems: 'center', gap: '0.5rem', marginBottom: '1.5rem' }}>
          <CheckCircle2 size={18} />
          <span>{saveMessage}</span>
        </div>
      )}

      {/* Case Header Card */}
      <div className="card" style={{ marginBottom: '1.5rem', padding: '2rem' }}>
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start', flexWrap: 'wrap', gap: '1rem', marginBottom: '1rem' }}>
          <div>
            <span style={{ fontSize: '0.825rem', color: 'var(--text-light)', textTransform: 'uppercase', letterSpacing: '0.04em' }}>
              Court Judgment / Legal Precedent
            </span>
            <h1 className="legal-heading" style={{ fontSize: '1.65rem', marginTop: '0.25rem', color: 'var(--text-main)' }}>
              {caseItem.case_title}
            </h1>
          </div>

          <div>
            {isVerified ? (
              <span className="badge badge-verified">
                ✓ Verified Official Source
              </span>
            ) : (
              <span className="badge badge-unverified">
                ⚠️ Unverified Reference
              </span>
            )}
          </div>
        </div>

        {/* Verification Status Banner */}
        {!isVerified && (
          <div className="alert alert-warning" style={{ fontSize: '0.875rem', marginBottom: '1.5rem' }}>
            <AlertTriangle size={18} style={{ flexShrink: 0 }} />
            <div>
              <strong>Precedent Verification Notice:</strong> This case reference was generated by AI based on legal training data. 
              The exact citation, court bench, and official text have not been directly retrieved from an authenticated law reporter 
              and must be independently verified by a licensed advocate prior to reliance in any court proceedings.
            </div>
          </div>
        )}

        {/* Structured Case Attributes */}
        <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(220px, 1fr))', gap: '1rem', padding: '1rem', backgroundColor: 'var(--bg-alt)', borderRadius: 'var(--radius-md)', marginBottom: '1.5rem' }}>
          <div>
            <div style={{ fontSize: '0.785rem', color: 'var(--text-light)', fontWeight: 600 }}>COURT / BENCH</div>
            <div style={{ fontSize: '0.95rem', fontWeight: 600, color: 'var(--text-main)' }}>
              {caseItem.court || 'Not available in retrieved source'}
            </div>
          </div>

          <div>
            <div style={{ fontSize: '0.785rem', color: 'var(--text-light)', fontWeight: 600 }}>CITATION / NUMBER</div>
            <div style={{ fontSize: '0.95rem', fontWeight: 600, color: 'var(--text-main)' }}>
              {caseItem.citation || 'Not available in retrieved source'}
            </div>
          </div>

          <div>
            <div style={{ fontSize: '0.785rem', color: 'var(--text-light)', fontWeight: 600 }}>JUDGMENT DATE / YEAR</div>
            <div style={{ fontSize: '0.95rem', fontWeight: 600, color: 'var(--text-main)' }}>
              {caseItem.judgment_date || 'Not available in retrieved source'}
            </div>
          </div>

          <div>
            <div style={{ fontSize: '0.785rem', color: 'var(--text-light)', fontWeight: 600 }}>AUTHENTICATED SOURCE</div>
            <div style={{ fontSize: '0.95rem', color: 'var(--text-main)' }}>
              {caseItem.source_url ? (
                <a href={caseItem.source_url} target="_blank" rel="noopener noreferrer">Official Link ↗</a>
              ) : (
                <span style={{ color: 'var(--text-light)' }}>None linked</span>
              )}
            </div>
          </div>
        </div>

        {/* Detailed Legal Analysis */}
        <div style={{ display: 'flex', flexDirection: 'column', gap: '1.5rem' }}>
          <div>
            <h3 style={{ fontSize: '1.05rem', color: 'var(--primary-navy)', marginBottom: '0.4rem' }}>
              Legal Issue Addressed
            </h3>
            <p style={{ color: 'var(--text-main)', fontSize: '0.95rem', lineHeight: '1.6' }}>
              {caseItem.legal_issue || 'Not available in retrieved source'}
            </p>
          </div>

          <div>
            <h3 style={{ fontSize: '1.05rem', color: 'var(--primary-navy)', marginBottom: '0.4rem' }}>
              Ratio Decidendi / Legal Principle
            </h3>
            <p style={{ color: 'var(--text-main)', fontSize: '0.95rem', lineHeight: '1.6' }}>
              {caseItem.principle || 'Not available in retrieved source'}
            </p>
          </div>

          <div>
            <h3 style={{ fontSize: '1.05rem', color: 'var(--primary-navy)', marginBottom: '0.4rem' }}>
              Relevance to Your Legal Dispute
            </h3>
            <p style={{ color: 'var(--text-main)', fontSize: '0.95rem', lineHeight: '1.6', backgroundColor: '#f8fafc', padding: '0.85rem', borderRadius: 'var(--radius-sm)', borderLeft: '3px solid var(--accent-gold)' }}>
              {caseItem.relevance || 'Not available in retrieved source'}
            </p>
          </div>
        </div>
      </div>
    </div>
  );
}
