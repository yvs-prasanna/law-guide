import React, { useState } from 'react';
import { ExternalLink, Bookmark, Check, AlertCircle, FileText } from 'lucide-react';

export default function CaseCard({
  caseItem,
  onViewDetails,
  onSaveCase,
  isSaved = false,
  saving = false,
}) {
  const [localSaved, setLocalSaved] = useState(isSaved);

  const handleSave = async () => {
    if (localSaved || saving) return;
    if (onSaveCase) {
      await onSaveCase(caseItem);
      setLocalSaved(true);
    }
  };

  const isVerified = caseItem.verification_status === 'verified';

  return (
    <div className="case-card">
      <div className="case-card-header">
        <div>
          <h3 className="case-title">{caseItem.case_title || 'Judicial Precedent Reference'}</h3>
          <div className="case-court-meta" style={{ marginTop: '0.4rem' }}>
            <span>🏛️ {caseItem.court || 'Supreme Court / High Court'}</span>
            {caseItem.judgment_date && <span>📅 {caseItem.judgment_date}</span>}
            {caseItem.citation && <span>📜 Citation: {caseItem.citation}</span>}
          </div>
        </div>

        <div>
          {isVerified ? (
            <span className="badge badge-verified" title="Confirmed official citation with source record">
              ✓ Verified Official Source
            </span>
          ) : (
            <span className="badge badge-unverified" title="AI-generated reference requiring independent verification against official law reporters">
              ⚠️ Unverified Precedent Reference
            </span>
          )}
        </div>
      </div>

      {/* Legal Issue */}
      {caseItem.legal_issue && (
        <div className="case-section-block">
          <div className="case-section-title">Legal Issue / Question of Law</div>
          <div className="case-section-content">{caseItem.legal_issue}</div>
        </div>
      )}

      {/* Relevant Principle */}
      {caseItem.principle && (
        <div className="case-section-block">
          <div className="case-section-title">Judicial Ratio / Legal Principle</div>
          <div className="case-section-content">{caseItem.principle}</div>
        </div>
      )}

      {/* Relevance to User */}
      {caseItem.relevance && (
        <div className="case-section-block">
          <div className="case-section-title">Relevance to Your Legal Issue</div>
          <div className="case-section-content" style={{ color: 'var(--text-main)', fontStyle: 'italic' }}>
            "{caseItem.relevance}"
          </div>
        </div>
      )}

      {/* Verification notice footnote */}
      <div style={{ display: 'flex', alignItems: 'center', gap: '0.4rem', fontSize: '0.785rem', color: 'var(--text-light)', marginTop: '0.75rem' }}>
        <AlertCircle size={13} style={{ color: 'var(--accent-gold)' }} />
        <span>Precedents generated by AI must be verified in law reports (AIR, SCC, SCR) by your advocate.</span>
      </div>

      {/* Card Actions */}
      <div className="case-card-actions">
        {onViewDetails && (
          <button
            onClick={() => onViewDetails(caseItem)}
            className="btn btn-secondary btn-sm"
          >
            <FileText size={14} />
            <span>View Full Details</span>
          </button>
        )}

        {caseItem.source_url && (
          <a
            href={caseItem.source_url}
            target="_blank"
            rel="noopener noreferrer"
            className="btn btn-secondary btn-sm"
          >
            <ExternalLink size={14} />
            <span>Open Original Source</span>
          </a>
        )}

        {onSaveCase && (
          <button
            onClick={handleSave}
            disabled={localSaved || saving}
            className={`btn btn-sm ${localSaved ? 'btn-outline-gold' : 'btn-secondary'}`}
            style={localSaved ? { cursor: 'default' } : {}}
          >
            {localSaved ? <Check size={14} /> : <Bookmark size={14} />}
            <span>{localSaved ? 'Saved to Library' : 'Save Case'}</span>
          </button>
        )}
      </div>
    </div>
  );
}
